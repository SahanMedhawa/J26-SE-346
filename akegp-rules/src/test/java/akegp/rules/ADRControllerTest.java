package akegp.rules;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;
import akegp.rules.api.ADRController;
import akegp.rules.api.ProjectRegistrationExceptionHandler;
import akegp.rules.repository.InMemoryADRRepository;
import akegp.rules.repository.InMemoryProjectRepository;
import akegp.rules.service.ADRServiceImpl;
import akegp.rules.service.ProjectRegistrationServiceImpl;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;

class ADRControllerTest {
  private MockMvc mockMvc;
  private UUID projectId;

  @BeforeEach
  void setUp() {
    var projectService = new ProjectRegistrationServiceImpl(new InMemoryProjectRepository());
    projectId =
        projectService
            .register(
                new akegp.rules.api.ProjectRegistrationRequest(
                    "Project", null, "https://github.com/example/project-" + UUID.randomUUID(),
                    java.util.Set.of(akegp.rules.domain.ArchitectureStyle.LAYERED)))
            .id();
    mockMvc =
        MockMvcBuilders.standaloneSetup(
                new ADRController(new ADRServiceImpl(new InMemoryADRRepository(), projectService, new TestReadableIdRepository())))
            .setControllerAdvice(new ProjectRegistrationExceptionHandler())
            .build();
  }

  @Test
  void preservesUuidRoutesAndRejectsReadableIdChanges() throws Exception {
    String request = """
        {"title":"Choose service boundaries","status":"PROPOSED",
        "context":"The system needs clear service boundaries.",
        "decision":"Define boundaries by business capability.",
        "consequences":"Teams will own services and contracts."}
        """;
    String base = "/api/rules/projects/" + projectId + "/adrs";
    mockMvc.perform(post(base).contentType(MediaType.APPLICATION_JSON)
        .content(request.replace("{", "{\"adrId\":\"ADR-999\",")))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.fieldErrors.adrId").value("ADR ID is generated by the backend; omit adrId"));
    var created = mockMvc.perform(post(base).contentType(MediaType.APPLICATION_JSON).content(request))
        .andExpect(status().isCreated()).andExpect(jsonPath("$.adrId").value("ADR-001"))
        .andExpect(jsonPath("$.projectId").value(projectId.toString())).andReturn();
    String uuid = com.jayway.jsonpath.JsonPath.read(created.getResponse().getContentAsString(), "$.id");
    mockMvc.perform(get(base + "/" + uuid)).andExpect(status().isOk())
        .andExpect(jsonPath("$.id").value(uuid));
    String update = request.replace("{", "{\"version\":1,").replace("PROPOSED", "ACCEPTED");
    mockMvc.perform(put(base + "/" + uuid).contentType(MediaType.APPLICATION_JSON)
        .content(update.replace("{", "{\"adrId\":\"ADR-999\",")))
        .andExpect(status().isBadRequest());
    mockMvc.perform(put(base + "/" + uuid).contentType(MediaType.APPLICATION_JSON).content(update))
        .andExpect(status().isOk()).andExpect(jsonPath("$.id").value(uuid))
        .andExpect(jsonPath("$.adrId").value("ADR-001")).andExpect(jsonPath("$.version").value(2));
    mockMvc.perform(delete(base + "/" + uuid)).andExpect(status().isNoContent());
    mockMvc.perform(get(base + "/" + uuid)).andExpect(status().isNotFound());
    mockMvc.perform(post(base).contentType(MediaType.APPLICATION_JSON).content(request))
        .andExpect(status().isCreated()).andExpect(jsonPath("$.adrId").value("ADR-002"));
  }

  @Test
  void createsAndListsADR() throws Exception {
    mockMvc
        .perform(
            post("/api/rules/projects/{projectId}/adrs", projectId)
                .contentType(MediaType.APPLICATION_JSON)
                .content(
                    """
                    {

                      "title": "Choose service boundaries",
                      "status": "PROPOSED",
                      "context": "The system needs clear service boundaries.",
                      "decision": "We will define boundaries by business capability.",
                      "consequences": "Teams will own services and contracts."
                    }
                    """))
        .andExpect(status().isCreated())
        .andExpect(jsonPath("$.version").value(1))
        .andExpect(jsonPath("$.linkedRuleCount").isEmpty())
        .andExpect(jsonPath("$.linkedRuleIds").isArray());

    mockMvc
        .perform(get("/api/rules/projects/{projectId}/adrs", projectId))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$[0].adrId").value("ADR-001"));
  }

  @Test
  void rejectsInvalidRequest() throws Exception {
    mockMvc
        .perform(
            post("/api/rules/projects/{projectId}/adrs", projectId)
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"adrId\":\"bad\",\"title\":\"x\",\"status\":\"PROPOSED\"}"))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.fieldErrors.adrId").exists());

    mockMvc
        .perform(
            post("/api/rules/projects/{projectId}/adrs", projectId)
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"adrId\":\"ADR-001\",\"title\":\"valid title\",\"status\":\"UNKNOWN\"}"))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.message").value("Request body contains invalid or unsupported values"));
  }
}
